function pickRandom(arr) {
  return arr[Math.floor(Math.random() * arr.length)];
}

function shuffleArray(arr) {
  const copy = [...arr];
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy;
}

function matchesKeyword(idea, keyword) {
  if (!keyword) return false;
  const kw = keyword.toLowerCase();
  return idea.topics.some(t => kw.includes(t) || t.includes(kw));
}

export function generateIdeas(formData) {
  const { niche, tone, contentTypes, theme } = formData;
  const keyword = ((theme || "") + " " + (niche || "")).toLowerCase();
  const hooks = TONE_HOOKS[tone] || TONE_HOOKS.friendly;

  const matched = IDEA_POOL.filter(i => matchesKeyword(i, keyword));
  const others  = IDEA_POOL.filter(i => !matchesKeyword(i, keyword));
  const ordered = [...shuffleArray(matched), ...shuffleArray(others)];

  const seen = new Set();
  const deduped = ordered.filter(i => {
    if (seen.has(i.title)) return false;
    seen.add(i.title);
    return true;
  });

  const enabledTypes = contentTypes && contentTypes.length > 0
    ? contentTypes
    : ["reels", "carousel", "stories", "talking_head"];

  return deduped.slice(0, 5).map((idea, idx) => {
    const preferred = idea.types.filter(t => enabledTypes.includes(t));
    const typeKey = preferred.length > 0
      ? preferred[idx % preferred.length]
      : enabledTypes[idx % enabledTypes.length];

    const cta = CTA_OPTIONS[idea.ctaIndex];

    return {
      id: idx + 1,
      title: idea.title,
      type: CONTENT_TYPE_LABELS[typeKey] || typeKey,
      typeKey,
      typeEmoji: CONTENT_TYPE_EMOJIS[typeKey] || "📌",
      description: idea.description,
      seriesHint: idea.seriesHint,
      duration: idea.duration,
      scenario: {
        hook: `${idea.hookCore}\n\n${pickRandom(hooks)}`,
        main: idea.mainBody,
        cta: cta.full,
        ctaShort: cta.short,
      },
    };
  });
}

